# create_sample_data.py
"""Creates the two sample attachments used by the pipeline (sales_report.pdf, summary_data.xlsx)."""
import os
from openpyxl import Workbook
from openpyxl.styles import Font
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
REPORTS_DIR = os.path.join(BASE_DIR, "data", "reports")

SALES = [
    ("Wireless Earbuds", 120, 4200.00),
    ("Smart Watch", 35, 3850.50),
    ("USB-C Hub", 80, 1999.17),
    ("Laptop Stand", 64, 1296.00),
    ("Mechanical Keyboard", 15, 1000.00),
]


def create_pdf(path):
    c = canvas.Canvas(path, pagesize=A4)
    _, height = A4
    c.setFont("Helvetica-Bold", 18)
    c.drawString(60, height - 70, "Daily Sales Report")
    c.setFont("Helvetica", 11)
    c.drawString(60, height - 95, "Generated by the Agentic Communication Automator (sample data)")
    y = height - 140
    c.setFont("Helvetica-Bold", 11)
    c.drawString(60, y, "Product")
    c.drawString(300, y, "Units")
    c.drawString(400, y, "Revenue (USD)")
    c.setFont("Helvetica", 11)
    for product, units, revenue in SALES:
        y -= 22
        c.drawString(60, y, product)
        c.drawString(300, y, str(units))
        c.drawString(400, y, f"{revenue:,.2f}")
    y -= 30
    c.setFont("Helvetica-Bold", 11)
    c.drawString(60, y, "Total")
    c.drawString(300, y, str(sum(s[1] for s in SALES)))
    c.drawString(400, y, f"{sum(s[2] for s in SALES):,.2f}")
    c.save()


def create_xlsx(path):
    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    ws.append(["Product", "Units", "Revenue (USD)"])
    for cell in ws[1]:
        cell.font = Font(bold=True)
    for row in SALES:
        ws.append(list(row))
    ws.append(["Total", f"=SUM(B2:B{len(SALES) + 1})", f"=SUM(C2:C{len(SALES) + 1})"])
    ws.column_dimensions["A"].width = 24
    ws.column_dimensions["C"].width = 16
    wb.save(path)


if __name__ == "__main__":
    os.makedirs(REPORTS_DIR, exist_ok=True)
    create_pdf(os.path.join(REPORTS_DIR, "sales_report.pdf"))
    create_xlsx(os.path.join(REPORTS_DIR, "summary_data.xlsx"))
    print(f"Sample files created in {REPORTS_DIR}")
